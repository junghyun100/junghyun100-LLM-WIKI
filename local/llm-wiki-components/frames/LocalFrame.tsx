import { PageFrame, PageFrameProps } from "../../quartz/components/frames/types"

/**
 * Custom page frame for LLM Wiki - renders header slot components directly
 * without the core Quartz Header wrapper that incorrectly uses baseUrl
 */
export const LocalFrame: PageFrame = {
  name: "local",
  render({
    componentData,
    header,
    beforeBody,
    pageBody: Content,
    afterBody,
    left,
    right,
    footer: Footer,
  }: PageFrameProps) {
    return (
      <>
        <div class="left sidebar">
          {left.map((BodyComponent) => (
            <BodyComponent {...componentData} />
          ))}
        </div>
        <div class="center">
          <div class="page-header">
            {/* Render header slot components directly - NO hardcoded Header wrapper */}
            {header.map((HeaderComponent) => (
              <HeaderComponent {...componentData} />
            ))}
            <div class="popover-hint">
              {beforeBody.map((BodyComponent) => (
                <BodyComponent {...componentData} />
              ))}
            </div>
          </div>
          <Content {...componentData} />
          <hr />
          <div class="page-footer">
            {afterBody.map((BodyComponent) => (
              <BodyComponent {...componentData} />
            ))}
          </div>
        </div>
        <div class="right sidebar">
          {right.map((BodyComponent) => (
            <BodyComponent {...componentData} />
          ))}
        </div>
        <Footer {...componentData} />
      </>
    )
  },
}